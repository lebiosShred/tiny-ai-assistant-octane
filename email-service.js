const fs = require('fs');
const path = require('path');

/**
 * Sends a real-time lead notification email to the configured administrator or SDR.
 * If SMTP credentials are not configured, it gracefully falls back to logging the 
 * complete HTML email content in the development logs and saving a mockup file.
 * 
 * @param {Object} lead New lead data object
 * @returns {Promise<boolean>} Success status of the email dispatch
 */
